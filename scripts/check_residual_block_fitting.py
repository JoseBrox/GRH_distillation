#!/usr/bin/env python3
"""Exact finite witnesses for the residual-block Fitting corrections.

The universal theorems are proved in notes/residual-block-fitting.md.
This script verifies concrete obstructions, finite-field repairs, the
factorial constant on falling factorials, and a character-evaluation
collision. It does not compute Selmer groups or verify an automorphy
application. It needs only the Python standard library.
"""

from itertools import product
import json
from math import factorial
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def valuation(n, prime):
    if n == 0:
        return None
    n = abs(n)
    out = 0
    while n % prime == 0:
        n //= prime
        out += 1
    return out


def falling_coefficients(degree):
    """Low-degree-first exact coefficients of X(X-1)...(X-degree+1)."""
    coefficients = [1]
    for root in range(degree):
        updated = [0] * (len(coefficients) + 1)
        for index, coefficient in enumerate(coefficients):
            updated[index] -= root * coefficient
            updated[index + 1] += coefficient
        coefficients = updated
    return coefficients


def evaluate(coefficients, point):
    out = 0
    for coefficient in reversed(coefficients):
        out = out * point + coefficient
    return out


def main():
    # Three identical one-dimensional representations of F_2.
    joint_image = {(a, a, a) for a in range(2)}
    target = set(product(range(2), repeat=3))
    assert len(joint_image) == 2 and len(target) == 8
    assert all({t[j] for t in joint_image} == {0, 1} for j in range(3))

    # Restrictions to the three saturated lines e_1, e_2, e_1+e_2.
    f2_rows = []
    for a, b in product(range(2), repeat=2):
        values = (a, b, (a + b) % 2)
        f2_rows.append({"row": [a, b], "restrictions": list(values)})
        assert 0 in values

    # F_4=F_2[t]/(t^2+t+1), represented by bits; addition is XOR.
    # For (a,b)=(1,t), all restrictions 1,t,1+t are nonzero.
    f4_row = (1, 2)
    f4_restrictions = (1, 2, 1 ^ 2)
    assert all(f4_restrictions)

    # Over Z the determinant product is a*b*(a+b).
    grid_values = []
    for a, b in product(range(4), repeat=2):
        value = a * b * (a + b)
        grid_values.append({"row": [a, b], "value": value,
                            "v2": valuation(value, 2)})
        assert value % 2 == 0
    finite_v2 = [r["v2"] for r in grid_values if r["v2"] is not None]
    assert min(finite_v2) == valuation(factorial(3), 2) == 1

    # Monic falling factorials attain exactly the factorial valuation
    # on the integer grid used in the polynomial lemma.
    factorial_witnesses = []
    for degree in range(1, 13):
        coefficients = falling_coefficients(degree)
        assert coefficients[-1] == 1
        values = [evaluate(coefficients, z) for z in range(degree + 1)]
        assert values[:-1] == [0] * degree
        assert values[-1] == factorial(degree)
        for prime in (2, 3, 5, 7):
            nonzero_valuations = [valuation(x, prime) for x in values if x]
            expected = valuation(factorial(degree), prime)
            assert min(nonzero_valuations) == expected
            factorial_witnesses.append({"degree": degree, "prime": prime,
                                       "minimum_grid_valuation": expected})

    # Units modulo 10 form C_4 generated by 3. Faithful characters are
    # represented by exponents 1 and 3 into fourth roots of unity.
    powers = [pow(3, a, 10) for a in range(4)]
    assert powers == [1, 3, 9, 7]
    norm = 11 ** 2
    exponent = powers.index(norm % 10)
    evaluations = [(character * exponent) % 4 for character in (1, 3)]
    assert norm % 10 == 1 and evaluations == [0, 0]
    assert 11 % 3 == 2  # Inert in Q(sqrt(-3)), hence norm 11^2.

    output = {
        "status": "passed",
        "scope": "Exact finite examples only; universal proofs are in the note.",
        "source": {
            "repository": "jimjamzola/RH-Alpoge-Reconstruction",
            "commit": "aa9c86bf2a7d29b08575641fecea19a2a603e87c",
            "path": "manuscript/sec17_twisted.tex",
            "sha256": "e90bd6bb4d76be5840b435356553e8b12a5e599b0bf3d0bf0af6a4252065b77a",
        },
        "repeated_blocks": {"individual_images_surjective": True,
                            "joint_image_cardinality": len(joint_image),
                            "product_cardinality": len(target)},
        "common_left_inverse": {"F2_rows": f2_rows,
                                "F4_row_bits": list(f4_row),
                                "F4_restrictions_bits": list(f4_restrictions)},
        "determinant_product": {"formula": "a*b*(a+b)",
                                "minimum_v2_on_grid_0_to_3": min(finite_v2),
                                "v2_of_3_factorial": valuation(factorial(3), 2),
                                "witness": {"row": [1, 1], "value": 2}},
        "falling_factorial_tests": factorial_witnesses,
        "character_collision": {"modulus": 10, "unit_generator": 3,
                                "faithful_character_exponents": [1, 3],
                                "auxiliary_prime": 11, "norm": norm,
                                "evaluation_exponents_mod_4": evaluations},
    }
    target_path = ROOT / "certificates/residual-block-fitting.json"
    target_path.write_text(json.dumps(output, indent=2) + "\n")
    print("Passed: repeated-block obstruction, F4 repair, exact factorial witnesses, "
          "and character collision.")
    print(target_path.relative_to(ROOT))


if __name__ == "__main__":
    main()
